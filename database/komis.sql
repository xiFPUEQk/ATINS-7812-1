BEGIN;

CREATE TABLE IF NOT EXISTS brands (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS car_models (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES brands(id),
  name text NOT NULL,
  UNIQUE (brand_id, name)
);

CREATE TABLE IF NOT EXISTS cars (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model_id integer NOT NULL REFERENCES car_models(id),
  vin varchar(17) NOT NULL UNIQUE,
  production_year integer NOT NULL CHECK (production_year >= 1990),
  mileage_km integer NOT NULL CHECK (mileage_km >= 0),
  price_pln numeric(12,2) NOT NULL CHECK (price_pln > 0),
  status text NOT NULL DEFAULT 'AVAILABLE'
    CHECK (status IN ('AVAILABLE','RESERVED','SOLD')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name text NOT NULL,
  last_name text NOT NULL,
  email text UNIQUE
);

CREATE TABLE IF NOT EXISTS sales (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  car_id integer NOT NULL UNIQUE REFERENCES cars(id),
  customer_id integer NOT NULL REFERENCES customers(id),
  sale_price_pln numeric(12,2) NOT NULL CHECK (sale_price_pln > 0),
  sold_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS cars_status_idx ON cars(status);
CREATE INDEX IF NOT EXISTS cars_model_idx ON cars(model_id);
CREATE INDEX IF NOT EXISTS sales_customer_idx ON sales(customer_id);

